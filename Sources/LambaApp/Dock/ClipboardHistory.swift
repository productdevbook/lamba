/// The last things copied (text and images), kept in memory only. Items that password managers
/// mark as concealed or transient are skipped.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    struct Item: Identifiable, Equatable {
        let id = UUID()
        let date: Date
        let text: String?
        let image: NSImage?
        /// The app that was in front when it was copied.
        let source: String?

        static func == (a: Item, b: Item) -> Bool { a.id == b.id }
    }

    @Published private(set) var items: [Item] = []

    private let limit = 20
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    /// Our own writes shouldn't come back as new items.
    private var ignoreChange: Int?

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
    }

    func copy(_ item: Item) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let text = item.text { pasteboard.setString(text, forType: .string) }
        else if let image = item.image { pasteboard.writeObjects([image]) }
        ignoreChange = pasteboard.changeCount
        changeCount = pasteboard.changeCount
        // Copying again moves it to the top.
        items.removeAll { $0.id == item.id }
        items.insert(Item(date: Date(), text: item.text, image: item.image, source: item.source), at: 0)
    }

    func remove(_ item: Item) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        if ignoreChange == changeCount { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            items.removeAll { $0.text == text }
            items.insert(Item(date: Date(), text: text, image: nil, source: source), at: 0)
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
                  let image = NSImage(pasteboard: pasteboard) {
            items.insert(Item(date: Date(), text: nil, image: image, source: source), at: 0)
        } else {
            return
        }
        if items.count > limit { items.removeLast(items.count - limit) }
    }
}

// MARK: - Tile

struct ClipboardTile: View {
    @ObservedObject var history = ClipboardHistory.shared
    var onDark = false
    @State private var frame: CGRect = .zero

    private var ink: Color { onDark ? .white : .primary }

    var body: some View {
        Button {
            DockPopover.shared.toggle(id: "clipboard", anchor: frame) { ClipboardPopover(history: history) }
        } label: {
            ZStack(alignment: .bottomTrailing) {
                Image(systemName: "doc.on.clipboard")
                    .font(.system(size: 18))
                    .foregroundStyle(ink.opacity(0.75))
                    .frame(width: 40, height: 40)
                if !history.items.isEmpty {
                    Text("\(min(history.items.count, 99))")
                        .font(.system(size: 9, weight: .bold, design: .rounded).monospacedDigit())
                        .foregroundStyle(.white)
                        .padding(.horizontal, 4)
                        .frame(minWidth: 15, minHeight: 15)
                        .background(Capsule().fill(Color(white: 0.35)))
                        .offset(x: 2, y: 1)
                }
            }
            .frame(width: 40, height: 40)
            .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(ink.opacity(0.06)))
            .contentShape(RoundedRectangle(cornerRadius: 12, style: .continuous))
        }
        .buttonStyle(.plain)
        .help(L10n.clipboardTitle)
        .accessibilityLabel(L10n.clipboardTitle)
        .frame(maxHeight: .infinity)
        .modifier(AnchorReader(frame: $frame))
        .onAppear { history.start() }
    }
}

// MARK: - Popover

struct ClipboardPopover: View {
    @ObservedObject var history: ClipboardHistory
    @State private var copiedID: UUID?

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                HStack(spacing: 6) {
                    Image(systemName: "doc.on.clipboard.fill").foregroundStyle(Color.accentColor)
                    Text(L10n.clipboardTitle)
                }
                .font(.system(size: 13, weight: .semibold))
                Spacer()
                if !history.items.isEmpty {
                    Button(action: history.clear) {
                        Label(L10n.clipboardClear, systemImage: "trash")
                            .font(.system(size: 11, weight: .medium))
                            .padding(.horizontal, 9).padding(.vertical, 4)
                            .background(Capsule().fill(Color.white.opacity(0.1)))
                            .contentShape(Capsule())
                    }
                    .buttonStyle(.plain)
                }
            }
            if history.items.isEmpty {
                Text(L10n.clipboardEmpty)
                    .font(.system(size: 12)).foregroundStyle(.secondary)
                    .frame(maxWidth: .infinity, minHeight: 80)
            } else {
                ScrollView {
                    VStack(spacing: 2) {
                        ForEach(history.items) { item in
                            ClipboardRow(item: item, copied: copiedID == item.id) { copy(item) }
                                .contextMenu { Button(L10n.clipboardRemove) { history.remove(item) } }
                        }
                    }
                }
                .frame(height: min(CGFloat(history.items.count) * 52, 420))
            }
            Text(L10n.clipboardFooter).font(.system(size: 10.5)).foregroundStyle(.tertiary)
        }
        .padding(12)
        .frame(width: 320)
    }

    private func copy(_ item: ClipboardHistory.Item) {
        history.copy(item)
        copiedID = history.items.first?.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { DockPopover.shared.close() }
    }
}

private struct ClipboardRow: View {
    let item: ClipboardHistory.Item
    let copied: Bool
    let action: () -> Void
    @State private var hovered = false

    var body: some View {
        Button(action: action) {
            HStack(spacing: 10) {
                preview
                VStack(alignment: .leading, spacing: 2) {
                    Text(title)
                        .font(.system(size: 12))
                        .lineLimit(2)
                        .truncationMode(.tail)
                        .frame(maxWidth: .infinity, alignment: .leading)
                    Text(detail).font(.system(size: 10.5)).foregroundStyle(.secondary)
                }
                if copied {
                    Image(systemName: "checkmark.circle.fill").foregroundStyle(Color.green)
                }
            }
            .padding(.horizontal, 6).padding(.vertical, 5)
            .frame(minHeight: 48)
            .background(RoundedRectangle(cornerRadius: 9, style: .continuous).fill(Color.white.opacity(hovered ? 0.09 : 0)))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .onHover { hovered = $0 }
    }

    @ViewBuilder private var preview: some View {
        if let image = item.image {
            Image(nsImage: image)
                .resizable()
                .aspectRatio(contentMode: .fill)
                .frame(width: 36, height: 36)
                .clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
        } else {
            Image(systemName: isLink ? "link" : "text.alignleft")
                .font(.system(size: 13, weight: .medium))
                .foregroundStyle(.secondary)
                .frame(width: 36, height: 36)
                .background(RoundedRectangle(cornerRadius: 6, style: .continuous).fill(Color.white.opacity(0.08)))
        }
    }

    private var isLink: Bool {
        guard let text = item.text, !text.contains(" ") else { return false }
        return text.hasPrefix("http://") || text.hasPrefix("https://")
    }

    private var title: String {
        if let text = item.text {
            return text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        }
        guard let image = item.image else { return "" }
        return "\(Int(image.size.width)) × \(Int(image.size.height))"
    }

    private var detail: String {
        if copied { return L10n.clipboardCopied }
        let ago = RelativeDateTimeFormatter()
        ago.locale = L10n.locale
        ago.unitsStyle = .short
        let when = item.date > Date().addingTimeInterval(-50) ? ago.localizedString(fromTimeInterval: 0) : ago.localizedString(for: item.date, relativeTo: Date())
        return [item.source, when].compactMap { $0 }.joined(separator: " · ")
    }
}
